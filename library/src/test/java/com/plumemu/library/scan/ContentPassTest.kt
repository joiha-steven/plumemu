    @Test
    fun onlyCartridgesAndHeaderedZipsAreReadPlayedThenFavouritesSmallestFirst() = runTest {
        write("gb/b-big.gb", GB_ROM + ByteArray(1024))
        write("gb/a-small.gb", TWIN_ROM)
        write("gb/c-played.gb", GB_ROM + ByteArray(4096))
        write("gb/d-favourite.gb", GB_ROM + ByteArray(2048))
        write("gb/copy/a-small.gb", TWIN_ROM)
        write("nes/smb.zip", TestNaming.zip("smb.nes", INES_HEADER + NES_CONTENT))
        write("nes/smb.7z", byteArrayOf(0x37, 0x7A, 0xBC.toByte(), 0xAF.toByte(), 0x27, 0x1C) + ByteArray(64))
        write("gba/zq.zip", TestNaming.zip("zq.gba", TestNaming.gbaRom()))
        write("psx/game.iso", ByteArray(64 * 1024))
        write("arcade/zorkfght.zip", TestNaming.zip("zf.rom", ByteArray(16)))
        File(fx.roms, "gb/huge.gb").also { RandomAccessFile(it, "rw").use { f -> f.setLength(64L * 1024 * 1024 + 1) }; it.setLastModified(FILE_TIME) }
        scan()
        val sql = fx.db.openHelper.writableDatabase
        sql.execSQL("INSERT INTO play (game_id, last_played_at, total_seconds) VALUES (${fx.game("c-played.gb").id}, 1, 60)")
        sql.execSQL("UPDATE game SET is_favorite = 1 WHERE id = ${fx.game("d-favourite.gb").id}")

        readContent()

        val opened = fx.tree.opened.toList()
        assertEquals("played first, then favourites", listOf("fs:gb/c-played.gb", "fs:gb/d-favourite.gb"), opened.take(2))
        val rest = opened.drop(2)
        assertEquals(
            "only loose cartridges and zips that may hide a header; no disc, arcade set, 7z, GBA zip or file over 64 MiB",
            setOf("fs:gb/a-small.gb", "fs:gb/copy/a-small.gb", "fs:nes/smb.zip", "fs:gb/b-big.gb"),
            rest.toSet(),
        )
        assertEquals(4, rest.size)
        val sizes = rest.map { File(fx.roms, it.removePrefix("fs:")).length() }
        assertEquals("smallest first", sizes.sorted(), sizes)
        // Both copies sharing a content key are named from it.
        assertTrue(fx.games().filter { it.fileName == "a-small.gb" }.all { it.title == "Zork Twins" })
        val smb = fx.game("smb.zip")
        assertEquals(NES_TITLE, smb.title)
        assertEquals(TestNaming.crcOf(NES_CONTENT), FingerprintCodec.decode(smb.fingerprint)?.crc32)
        assertEquals("nothing left", ContentReadResult(), readContent())
    }

    @Test
    fun aBudgetStopsBetweenFilesAndTheNextSliceGoesOn() = runTest {
        write("gb/mario3.gb", GB_ROM)
        write("gb/twins.gb", TWIN_ROM)
        scan()
        assertEquals(ContentReadResult(moreLeft = true), readContent(ContentReadBudget(maxMillis = 0)))
        assertEquals(emptyList<String>(), fx.tree.opened)

        val first = readContent(ContentReadBudget(maxBytes = 1))
        assertEquals(1, first.read)
        assertTrue(first.moreLeft)
        assertEquals(listOf("fs:gb/twins.gb"), fx.tree.opened)
        assertEquals("mario3", fx.game("mario3.gb").title.lowercase())

        val second = readContent(ContentReadBudget(maxBytes = 1))
        assertEquals(listOf("fs:gb/mario3.gb"), fx.tree.opened)
        assertEquals(1, second.read)
        assertEquals(GB_TITLE, fx.game("mario3.gb").title)
        assertEquals(ContentReadResult(), readContent(ContentReadBudget(maxBytes = 1)))
    }

    @Test
    fun aCallerStopStopsBetweenFilesWritesWhatWasReadAndTheNextRunGoesOn() = runTest {
        // The app stops the pass while a game is played.
        write("gb/mario3.gb", GB_ROM)
        write("gb/twins.gb", TWIN_ROM)
        scan()
        var asked = 0
        val first = readContent(ContentReadBudget(stopBeforeNextFile = { asked++ > 0 }))
        assertEquals(1, first.read)
        assertEquals(1, first.written)
        assertTrue(first.moreLeft)
        assertEquals("one file opened, the second never", listOf("fs:gb/twins.gb"), fx.tree.opened)
        assertEquals(2, asked)

        val second = readContent(ContentReadBudget(stopBeforeNextFile = { false }))
        assertEquals("the next run reads only the file left", listOf("fs:gb/mario3.gb"), fx.tree.opened)
        assertEquals(1, second.read)
        assertEquals(GB_TITLE, fx.game("mario3.gb").title)
        assertEquals(ContentReadResult(), readContent())
    }

    @Test
    fun cancellingStopsBeforeTheNextFileAndLeavesRowsWholeOrUntouched() = runBlocking {
        write("gb/mario3.gb", GB_ROM)
        write("gb/twins.gb", TWIN_ROM)
        scan()
        val before = fx.games().associateBy { it.id }
        val opened = CompletableDeferred<Unit>()
        val release = CompletableDeferred<Unit>()
        fx.tree.beforeQuery = { id ->
            if (id == "fs:gb/twins.gb") {
                opened.complete(Unit)
                runBlocking { release.await() }
            }
        }
        val run = async { readContent() }
        opened.await()
        // Cancel first, then release the hook: releasing before the cancel lands lets the pass
        // reach the next file on a loaded machine.
        run.cancel()
        release.complete(Unit)
        run.join()
        assertEquals(listOf("fs:gb/twins.gb"), fx.tree.opened)
        for (game in fx.games()) {
            val old = before.getValue(game.id)
            val stamped = game.fingerprint != old.fingerprint
            // Whole: fingerprint, keys and name written together; untouched: all as before.
            assertEquals(stamped, game.fixKeys != old.fixKeys)
            assertEquals(stamped, game.title != old.title)
        }
    }

    private fun matched(key: String, gameId: Long? = null, title: String, pictures: String, personChoice: Boolean = false) = ScrapedGameEntity(
        scrapeKey = key,
        gameId = gameId,
        outcome = ScrapeOutcome.MATCHED,
        screenScraperId = "1",
        matchedBy = if (personChoice) ScrapeMatchedBy.NAME else ScrapeMatchedBy.HASH,
        isPersonChoice = personChoice,
        scrapedAt = 1,
        detailsJson = "{}",
        title = title,
        year = 1990,
        publisher = "Testsoft",
        players = "1",
        genre = "Action",
        pictures = pictures,
        hasBoxFront = true,
    )

    private companion object {
        const val FILE_TIME = 1_600_000_000_000L
        const val GB_TITLE = "Super Zork Bros. 3"
        const val NES_TITLE = "Zork Adventure"
        const val ATARI_TITLE = "Zork Pitfall"
        val ATARI_ROM = ByteArray(4096) { (it * 17 + 9).toByte() }

        /** No valid Game Boy header: a QUICK read gives no code, no key. */
        val GB_ROM = ByteArray(32 * 1024) { (it * 13 + 5).toByte() }
        val TWIN_ROM = ByteArray(16 * 1024) { (it * 31 + 7).toByte() }

        /** iNES header (2 x 16 KB PRG, 1 x 8 KB CHR) and the content the pack lists. */
        val INES_HEADER = ByteArray(16).also {
            "NES\u001A".toByteArray().copyInto(it)
            it[4] = 2
            it[5] = 1
        }
        val NES_CONTENT = ByteArray(40 * 1024) { (it * 11 + 1).toByte() }
    }
}
