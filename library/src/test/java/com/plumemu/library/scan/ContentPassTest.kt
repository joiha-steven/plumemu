    @Test
    fun anUnreadableFileIsLoggedAndGivenUpOnAfterAFewRuns() = runTest {
        write("gb/mario3.gb", GB_ROM)
        scan()
        val id = fx.game("mario3.gb").id
        fx.tree.failingReads += "fs:gb/mario3.gb"
        repeat(ContentPass.MAX_FAILED_READS) {
            val result = readContent()
            assertEquals(1, result.failed)
            assertEquals(listOf("fs:gb/mario3.gb"), fx.tree.opened)
            assertEquals("mario3", fx.game("mario3.gb").title.lowercase())
        }
        assertEquals("not read again", ContentReadResult(), readContent())
        assertEquals(emptyList<String>(), fx.tree.opened)
        // Named again from the cache (a newer pack): the stamp stays, still not read.
        fx.db.identifyDao().markSystemsToNameAgain(listOf("gb"))
        fx.scanner(naming = naming, rules = rules).nameWaiting().toList()
        assertEquals("not read after a naming from the cache", ContentReadResult(), readContent())
        val lines = ShadowLog.getLogs().map { it.msg }
        assertTrue(lines.any { it.contains("game $id content read failed (ClosedChannelException)") })
        assertTrue(lines.any { it.startsWith("Content pass done: 0 read, 0 renamed, 1 failed") })
        assertFalse(lines.any { it.contains("mario", ignoreCase = true) || it.contains(".gb") })
        assertTrue(ShadowLog.getLogs().none { it.throwable != null })

        // The file changes: a new QUICK read, so it is tried again.
        fx.tree.failingReads.clear()
        File(fx.roms, "gb/mario3.gb").setLastModified(FILE_TIME + 60_000)
        scan()
        assertEquals(1, readContent().read)
        assertEquals(GB_TITLE, fx.game("mario3.gb").title)
    }

