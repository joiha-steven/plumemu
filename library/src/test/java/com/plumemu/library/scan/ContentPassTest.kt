    @Test
    fun aRowThatChangedWhileItsFileWasReadIsNotWritten() = runTest {
        write("gb/mario3.gb", GB_ROM)
        scan()
        val game = fx.game("mario3.gb")
        // A rescan sees the file changed while the pass reads it.
        fx.tree.beforeQuery = { id ->
            if (id == "fs:gb/mario3.gb") {
                fx.db.openHelper.writableDatabase.execSQL("UPDATE game SET modified_at = modified_at + 1000, needs_identify = 1 WHERE id = ${game.id}")
            }
        }
        val result = readContent()
        assertEquals(1, result.skipped)
        assertEquals("a skipped row is no progress", 0, result.written)
        val after = fx.game("mario3.gb")
        assertEquals(game.title, after.title)
        assertEquals(game.fingerprint, after.fingerprint)
        assertEquals(game.fixKeys, after.fixKeys)
    }

    @Test
