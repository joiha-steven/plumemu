/**
 * The content pass: loose cartridges and headered zips read whole for
 * their content CRC, named again from it, their box art carried over, and everything it must
 * leave alone. Generated bytes and made-up titles only.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class ContentPassTest {
    @get:Rule
    val temp = TemporaryFolder()

    private lateinit var fx: ScanFixture
    private lateinit var naming: GameNaming

    private val rules = TestRules.ALL + listOf(
        SystemRule("gb", setOf("gb"), setOf("gb", "zip")),
        SystemRule("nes", setOf("nes"), setOf("nes", "zip", "7z")),
        SystemRule("atari2600", setOf("atari2600"), setOf("a26", "bin", "zip")),
    )

    @Before
    fun setUp() {
        ShadowLog.clear()
        fx = ScanFixture(temp.newFolder("fixture"), copyFixtures = false)
        naming = TestNaming.naming(
            temp.newFolder("packs"),
            crcReleases = mapOf(
                "gb" to listOf(GB_TITLE to GB_ROM, "Zork Twins" to TWIN_ROM),
                "gba" to listOf("Zork Quest II" to TestNaming.gbaRom()),
                "nes" to listOf(NES_TITLE to NES_CONTENT),
                "atari2600" to listOf(ATARI_TITLE to ATARI_ROM),
            ),
        )
    }

    @After
    fun tearDown() = fx.close()

    private fun write(path: String, bytes: ByteArray) =
        File(fx.roms, path).apply { parentFile?.mkdirs(); writeBytes(bytes); setLastModified(FILE_TIME) }

    private suspend fun scan() {
        fx.roms.walkTopDown().filter { it.isDirectory }.forEach { it.setLastModified(ScanFixture.BASE_TIME + 10_000L * ++scans) }
        fx.scanner(naming = naming, rules = rules).scan().toList()
    }

    private var scans = 0

    private suspend fun readContent(budget: ContentReadBudget = ContentReadBudget()): ContentReadResult {
        fx.tree.opened.clear()
        return fx.scanner(naming = naming, rules = rules).readContent(budget)
    }

    @Test
    fun aBadlyNamedLooseCartridgeIsNamedFromItsContentAndNeverReadAgain() = runTest {
        write("gb/mario3.gb", GB_ROM)
        scan()
        val before = fx.game("mario3.gb")
        assertEquals("QUICK: named by its file name", NameTrustNames.FILE_NAME, before.nameTrust)
        assertEquals("QUICK: no content key", "", before.fixKeys)

        val result = readContent()

        assertEquals(listOf("fs:gb/mario3.gb"), fx.tree.opened)
        assertEquals(ContentReadResult(read = 1, written = 1, renamed = 1, bytesRead = GB_ROM.size.toLong(), millis = 0), result)
        val after = fx.game("mario3.gb")
        assertEquals(GB_TITLE, after.title)
        assertEquals("IDENTIFIER_EXACT", after.nameTrust)
        assertEquals(TestNaming.crcOf(GB_ROM), FingerprintCodec.decode(after.fingerprint)?.crc32)
        assertTrue(FixKeys.split(after.fixKeys).first().startsWith("crc:"))

        // A later naming from the cache (a newer pack, new rules) and a later scan read nothing,
        // and the pass has nothing left to read.
        fx.db.identifyDao().markSystemsToNameAgain(listOf("gb"))
        fx.tree.opened.clear()
        fx.scanner(naming = naming, rules = rules).nameWaiting().toList()
        File(fx.roms, "gb/other.txt").writeText("x")
        scan()
        assertEquals(emptyList<String>(), fx.tree.opened)
        assertEquals(GB_TITLE, fx.game("mario3.gb").title)
        assertEquals(ContentReadResult(), readContent())
        assertEquals(emptyList<String>(), fx.tree.opened)
    }

    @Test
    fun aLooseCartridgeOfASystemWithoutAHeaderReaderIsNamedByItsWholeFileCrc() = runTest {
        write("atari2600/pitfal.a26", ATARI_ROM)
        write("psx/disc.bin", ATARI_ROM)
        scan()
        assertEquals("", fx.game("pitfal.a26").fixKeys)

        val result = readContent()

        assertEquals("only the cartridge is read", listOf("fs:atari2600/pitfal.a26"), fx.tree.opened)
        assertEquals(1, result.renamed)
        val after = fx.game("pitfal.a26")
        assertEquals(ATARI_TITLE, after.title)
        assertEquals("IDENTIFIER_EXACT", after.nameTrust)
        assertEquals(TestNaming.crcOf(ATARI_ROM), FingerprintCodec.decode(after.fingerprint)?.crc32)
        assertTrue(FixKeys.split(after.fixKeys).first().startsWith("crc:"))
        assertEquals("a disc system is not selected", NameTrustNames.FILE_NAME, fx.game("disc.bin").nameTrust)
    }

    @Test
    fun aPersonsFixKeepsItsNameAndFollowsTheNewKey() = runTest {
        write("gb/mario3.gb", GB_ROM)
        scan()
        val dao = fx.db.identifyDao()
        val game = fx.game("mario3.gb")
        dao.setFix(game.id, NameFixKind.OWN_NAME, "My Mario", "my mario", null, fixedAt = 1)

        assertEquals(0, readContent().renamed)

        val after = fx.game("mario3.gb")
        assertEquals("My Mario", after.title)
        assertEquals(NameTrustNames.PERSON_FIX, after.nameTrust)
        val crcKey = FixKeys.split(after.fixKeys).first()
        assertTrue(crcKey.startsWith("crc:"))
        assertEquals("My Mario", dao.fixesByKeys(listOf(crcKey)).single().title)
    }

    @Test
    fun boxArtFollowsTheNewKeyWhenTheTitleStays() = runTest {
        write("gba/Zork Quest 2 (USA).gba", TestNaming.gbaRom())
        scan()
        val game = fx.game("Zork Quest 2 (USA).gba")
        val oldKey = FixKeys.split(game.fixKeys).single()
        assertTrue(oldKey.startsWith("code:"))
        val scraped = fx.db.scrapedGameDao()
        scraped.insertOrReplace(matched(oldKey, title = game.title, pictures = "box-front pictures"))

        readContent()

        val after = fx.game("Zork Quest 2 (USA).gba")
        assertEquals(game.title, after.title)
        val newKey = FixKeys.split(after.fixKeys).first()
        assertTrue(newKey.startsWith("crc:"))
        val copied = scraped.get(newKey)
        assertNotNull("copied to the new key", copied)
        assertEquals(scraped.get(oldKey)!!.copy(scrapeKey = newKey, gameId = null), copied)
        assertEquals("box-front pictures", copied!!.pictures)
        assertNotNull("the old row stays for other copies", scraped.get(oldKey))
    }

    @Test
    fun boxArtIsAskedAgainWhenTheTitleChangesButAPersonsPickAlwaysFollows() = runTest {
        write("gb/mario3.gb", GB_ROM)
        write("gb/twins.gb", TWIN_ROM)
        scan()
        val renamed = fx.game("mario3.gb")
        val picked = fx.game("twins.gb")
        val scraped = fx.db.scrapedGameDao()
        val renamedOldKey = NameFixEntity.rowKey(renamed.id)
        val pickedOldKey = NameFixEntity.rowKey(picked.id)
        scraped.insertOrReplace(matched(renamedOldKey, gameId = renamed.id, title = renamed.title, pictures = "a"))
        scraped.insertOrReplace(matched(pickedOldKey, gameId = picked.id, title = "Zork Twins Picked", pictures = "b", personChoice = true))
        fx.db.scrapedGameDao().showScraperName(picked.id, "Zork Twins Picked", "zork twins picked", NameTrustNames.SCRAPER_PERSON_CHOICE, picked.nameTrust)

        readContent()

        val renamedNow = fx.game("mario3.gb")
        assertEquals(GB_TITLE, renamedNow.title)
        assertNull("title changed: asked again by CRC", scraped.get(FixKeys.split(renamedNow.fixKeys).first()))
        assertNotNull(scraped.get(renamedOldKey))

        val pickedNow = fx.game("twins.gb")
        assertEquals("the pick's title stays", "Zork Twins Picked", pickedNow.title)
        assertEquals(NameTrustNames.SCRAPER_PERSON_CHOICE, pickedNow.nameTrust)
        val pick = scraped.get(FixKeys.split(pickedNow.fixKeys).first())
        assertNotNull("the pick follows the new key", pick)
        assertTrue(pick!!.isPersonChoice)
        assertEquals("b", pick.pictures)
    }

    @Test
    fun aPersonsPickReplacesAnAutomaticAnswerAnotherCopyLeftUnderTheNewKey() = runTest {
        for (outcome in listOf(ScrapeOutcome.MATCHED, ScrapeOutcome.NO_MATCH)) {
            fx.db.scanDao().forgetLibrary()
            fx.db.openHelper.writableDatabase.execSQL("DELETE FROM scraped_game")
            fx.roms.deleteRecursively()
            // The same ROM loose and zipped: the zip has its content key from its directory at QUICK.
            write("gb/foo.gb", GB_ROM)
            write("gb/zipped/foo.zip", TestNaming.zip("foo.gb", GB_ROM))
            scan()
            val loose = fx.game("foo.gb")
            val zipKey = FixKeys.split(fx.game("foo.zip").fixKeys).first()
            assertTrue(zipKey.startsWith("crc:"))
            val scraped = fx.db.scrapedGameDao()
            scraped.insertOrReplace(matched(zipKey, title = "Wrong Automatic", pictures = "auto").copy(outcome = outcome))
            scraped.insertOrReplace(matched(NameFixEntity.rowKey(loose.id), gameId = loose.id, title = "Foo Picked", pictures = "picked", personChoice = true))
            scraped.showScraperName(loose.id, "Foo Picked", "foo picked", NameTrustNames.SCRAPER_PERSON_CHOICE, loose.nameTrust)

            readContent()

            val after = fx.game("foo.gb")
            assertEquals(zipKey, FixKeys.split(after.fixKeys).first())
            assertEquals("$outcome: the pick's title stays", "Foo Picked", after.title)
            assertEquals(NameTrustNames.SCRAPER_PERSON_CHOICE, after.nameTrust)
            val now = scraped.get(zipKey)!!
            assertTrue("$outcome: the pick replaced the automatic row", now.isPersonChoice)
            assertEquals("picked", now.pictures)
        }
    }

