package com.plumemu.library.scan

import com.plumemu.coredata.db.NameFixKind
import com.plumemu.coredata.db.NameTrustNames
import com.plumemu.library.TestRules
import com.plumemu.library.matching.SystemRule
import kotlinx.coroutines.flow.toList
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.File

/**
 * A small library of badly named loose files whose bytes have the CRC of
 * an entry in a (test) name pack. A QUICK scan names them by file name; the content pass should
 * name them by content. The counts are a ratchet: when a change names more of them, raise
 * [FLOOR_AFTER] (and add cases); never lower it, and never lower the cases to keep it green.
 * Made-up titles and generated bytes only; the real-library measurement is made on the device.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class ContentCorpusTest {
    @get:Rule
    val temp = TemporaryFolder()

    private lateinit var fx: ScanFixture
    private lateinit var naming: GameNaming

    private val rules = TestRules.ALL + listOf(
        SystemRule("gb", setOf("gb"), setOf("gb", "zip")),
        SystemRule("nes", setOf("nes"), setOf("nes", "zip")),
        SystemRule("atari2600", setOf("atari2600"), setOf("a26", "bin", "zip")),
        SystemRule("pcengine", setOf("pcengine"), setOf("pce", "zip")),
    )

    /** One corpus file: where it lies, its bytes, and the title it must end up with. */
    private class Case(val path: String, val bytes: ByteArray, val expected: String)

    private val cases = listOf(
        Case("nes/mario3.nes", INES_HEADER + NES_PRG, "Zork Bros. 3"),
        Case("nes/SMB3 (U) [!].nes", INES_HEADER + NES_PRG_2, "Zork Bros. 2"),
        Case("snes/zelda.sfc", TestNaming.ZIPPED_ROM, "Zork Quest"),
        // A 512-byte copier header in front: the content CRC leaves it out.
        Case("snes/quest headered.smc", ByteArray(512) + TestNaming.ZIPPED_ROM, "Zork Quest"),
        Case("gb/pkmn red.gb", GB_RED, "Zork Pocket Red"),
        Case("atari2600/pitfall.a26", ATARI, "Zork Pitfall"),
        Case("pcengine/bonk.pce", PCE, "Zork Cave Boy"),
        // The name says another game: the content wins.
        Case("gb/Zork Pocket Red (USA).gb", GB_BLUE, "Zork Pocket Blue"),
        // Named well enough by its file name already.
        Case("gb/Zork Twins (USA).gb", GB_TWINS, "Zork Twins"),
    )

    @Before
    fun setUp() {
        fx = ScanFixture(temp.newFolder("fixture"), copyFixtures = false)
        naming = TestNaming.naming(
            temp.newFolder("packs"),
            crcReleases = mapOf(
                "nes" to listOf("Zork Bros. 3" to NES_PRG, "Zork Bros. 2" to NES_PRG_2),
                "gb" to listOf("Zork Pocket Red" to GB_RED, "Zork Pocket Blue" to GB_BLUE, "Zork Twins" to GB_TWINS),
                "atari2600" to listOf("Zork Pitfall" to ATARI),
                "pcengine" to listOf("Zork Cave Boy" to PCE),
            ),
        )
    }

    @After
    fun tearDown() = fx.close()

    private fun write(path: String, bytes: ByteArray) =
        File(fx.roms, path).apply { parentFile?.mkdirs(); writeBytes(bytes); setLastModified(FILE_TIME) }

    private suspend fun scan() {
        fx.roms.walkTopDown().filter { it.isDirectory }.forEach { it.setLastModified(ScanFixture.BASE_TIME + 10_000L * ++scans) }
        fx.scanner(naming = naming, rules = rules).scan().toList()
    }

    private var scans = 0

    private suspend fun correct(): Int {
        val titles = fx.games().associate { it.fileName to it.title }
        return cases.count { titles[File(it.path).name] == it.expected }
    }

    @Test
    fun contentNamesTheBadlyNamedCorpusAndNothingElseChanges() = runTest {
        cases.forEach { write(it.path, it.bytes) }
        write("gb/unknown game.gb", ByteArray(8192) { (it * 5 + 2).toByte() })
        scan()

        val unknownBefore = fx.game("unknown game.gb")
        val before = correct()
        fx.scanner(naming = naming, rules = rules).readContent(ContentReadBudget())
        val after = correct()
        val unknown = fx.game("unknown game.gb")
        assertEquals("a CRC in no pack changes nothing", unknownBefore.title, unknown.title)
        assertEquals(NameTrustNames.FILE_NAME, unknown.nameTrust)

        println("content corpus: $before of ${cases.size} named right by file name, $after after the content pass")
        // Ratchet. BEFORE is what a QUICK scan does today (only the well-named file is right).
        assertEquals("by file name", BEFORE_TODAY, before)
        assertTrue("content pass named $after, floor is $FLOOR_AFTER", after >= FLOOR_AFTER)
        assertEquals("every case built to match is named", cases.size, FLOOR_AFTER)
    }

    @Test
    fun aFileInNoPackKeepsItsCleanedNameAndAPersonsFixStays() = runTest {
        write("gb/unknown game.gb", ByteArray(8192) { (it * 5 + 2).toByte() })
        write("gb/fixed.gb", GB_RED)
        scan()
        val unknownBefore = fx.game("unknown game.gb")
        val fixed = fx.game("fixed.gb")
        fx.db.identifyDao().setFix(fixed.id, NameFixKind.OWN_NAME, "My Own Name", "my own name", null, fixedAt = 1)

        fx.scanner(naming = naming, rules = rules).readContent(ContentReadBudget())

        val unknown = fx.game("unknown game.gb")
        assertEquals("a CRC in no pack changes nothing", unknownBefore.title, unknown.title)
        assertEquals(NameTrustNames.FILE_NAME, unknown.nameTrust)
        assertEquals("My Own Name", fx.game("fixed.gb").title)
        assertEquals(NameTrustNames.PERSON_FIX, fx.game("fixed.gb").nameTrust)
    }

    private companion object {
        const val FILE_TIME = 1_600_000_000_000L

        /** Raise when a change names more files of this corpus; never lower. */
        const val FLOOR_AFTER = 9

        /** What the file names alone give today: only "Zork Twins (USA).gb" is right. */
        const val BEFORE_TODAY = 1

        val INES_HEADER = ByteArray(16).also {
            "NES\u001A".toByteArray().copyInto(it)
            it[4] = 2
            it[5] = 1
        }
        val NES_PRG = ByteArray(40 * 1024) { (it * 11 + 1).toByte() }
        val NES_PRG_2 = ByteArray(40 * 1024) { (it * 19 + 3).toByte() }
        val GB_RED = ByteArray(32 * 1024) { (it * 13 + 5).toByte() }
        val GB_BLUE = ByteArray(32 * 1024) { (it * 23 + 1).toByte() }
        val GB_TWINS = ByteArray(16 * 1024) { (it * 31 + 7).toByte() }
        val ATARI = ByteArray(4096) { (it * 17 + 9).toByte() }
        val PCE = ByteArray(8192) { (it * 29 + 4).toByte() }
    }
}
