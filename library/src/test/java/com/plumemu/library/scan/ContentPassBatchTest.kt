package com.plumemu.library.scan

import androidx.room.InvalidationTracker
import com.plumemu.library.TestRules
import com.plumemu.library.matching.SystemRule
import com.plumemu.library.naming.FingerprintCodec
import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.async
import kotlinx.coroutines.flow.toList
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.shadows.ShadowLog
import java.io.File
import java.util.concurrent.atomic.AtomicInteger

/**
 * The content pass writes one page of results in one transaction: a transaction per file made
 * every Room observer of `game` re-query the whole library once per file (10,000 re-queries on a
 * 10,000-game library while the pass ran). Generated bytes and file-name titles only.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class ContentPassBatchTest {
    @get:Rule
    val temp = TemporaryFolder()

    private lateinit var fx: ScanFixture
    private lateinit var naming: GameNaming
    private val rules = TestRules.ALL + listOf(SystemRule("gb", setOf("gb"), setOf("gb", "zip")))

    @Before
    fun setUp() {
        ShadowLog.clear()
        fx = ScanFixture(temp.newFolder("fixture"), copyFixtures = false)
        naming = TestNaming.naming(temp.newFolder("packs"), crcReleases = emptyMap())
    }

    @After
    fun tearDown() = fx.close()

    /** [count] distinct 1 KB cartridges, `game000.gb` and on. */
    private suspend fun scanCartridges(count: Int) {
        repeat(count) { i ->
            File(fx.roms, "gb/game%03d.gb".format(i)).apply {
                parentFile?.mkdirs()
                writeBytes(ByteArray(1024) { (it * 7 + i * 13 + 1).toByte() })
                setLastModified(FILE_TIME)
            }
        }
        fx.roms.walkTopDown().filter { it.isDirectory }.forEach { it.setLastModified(ScanFixture.BASE_TIME + 10_000L) }
        fx.scanner(naming = naming, rules = rules).scan().toList()
    }

    private suspend fun readContent(budget: ContentReadBudget = ContentReadBudget()): ContentReadResult {
        fx.tree.opened.clear()
        return fx.scanner(naming = naming, rules = rules).readContent(budget)
    }

    private suspend fun isDone(fileName: String) =
        fx.game(fileName).fingerprint.orEmpty().contains(FingerprintCodec.CONTENT_READ_DONE_MARK)

    @Test
    fun aPassInvalidatesTheGameTableOncePerPageNotOncePerFile() = runTest {
        scanCartridges(120)
        val invalidations = AtomicInteger()
        fx.db.invalidationTracker.addObserver(
            object : InvalidationTracker.Observer("game") {
                override fun onInvalidated(tables: Set<String>) {
                    invalidations.incrementAndGet()
                }
            },
        )

        val result = readContent()

        assertEquals(120, result.read)
        assertEquals(120, result.written)
        assertTrue(
            "game invalidated ${invalidations.get()} times for 120 files; at most one per page of 50 (3)",
            invalidations.get() <= 3,
        )
    }

    @Test
    fun aBudgetSpentMidPageWritesWhatWasReadAndTheNextRunGoesOnFromThere() = runTest {
        scanCartridges(5)

        // 1 KB each: the check before the fourth file sees 3 KB read.
        val first = readContent(ContentReadBudget(maxBytes = 2500))

        assertTrue(first.moreLeft)
        assertEquals(3, first.read)
        assertEquals("every file read is written, not dropped with the page", 3, first.written)
        val firstOpened = fx.tree.opened.toList()
        assertEquals(3, firstOpened.size)
        for (id in firstOpened) assertTrue(id, isDone(id.substringAfterLast('/')))

        val second = readContent()

        assertFalse(second.moreLeft)
        assertEquals(2, second.written)
        assertTrue("nothing read twice: ${fx.tree.opened}", fx.tree.opened.none { it in firstOpened })
        assertEquals(ContentReadResult(), readContent())
    }

    @Test
    fun aRowChangedBetweenReadAndWriteIsStaleWhileTheRestOfItsBatchIsWritten() = runTest {
        scanCartridges(3)
        val changed = fx.game("game001.gb")
        var hooked = false
        fx.tree.beforeQuery = { id ->
            if (id == "fs:gb/game001.gb" && !hooked) {
                hooked = true
                fx.db.openHelper.writableDatabase.execSQL(
                    "UPDATE game SET modified_at = modified_at + 1000, needs_identify = 1 WHERE id = ${changed.id}",
                )
            }
        }

        val result = readContent()

        assertEquals(3, result.read)
        assertEquals(1, result.skipped)
        assertEquals(2, result.written)
        assertTrue(isDone("game000.gb"))
        assertTrue(isDone("game002.gb"))
        val after = fx.game("game001.gb")
        assertEquals("the scan's change is not overwritten", changed.fingerprint, after.fingerprint)
        assertEquals(changed.modifiedAt + 1000, after.modifiedAt)
        assertTrue(after.needsIdentify)
    }

    @Test
    fun aRowWhoseWriteFailsLosesOnlyItsOwnResultNotTheBatch() = runTest {
        scanCartridges(3)
        val bad = fx.game("game001.gb")
        // The database refuses this one row's write (stands in for any SQLite error on one row).
        fx.db.openHelper.writableDatabase.execSQL(
            "CREATE TRIGGER refuse_one BEFORE UPDATE OF fingerprint ON game WHEN NEW.id = ${bad.id} " +
                "BEGIN SELECT RAISE(ABORT, 'refused by the test'); END",
        )

        val result = readContent()

        assertEquals(3, result.read)
        assertEquals(2, result.written)
        assertEquals(1, result.skipped)
        assertTrue(isDone("game000.gb"))
        assertTrue(isDone("game002.gb"))
        assertEquals(bad.fingerprint, fx.game("game001.gb").fingerprint)
        assertTrue(
            "the failed write is logged",
            ShadowLog.getLogs().any { "game ${bad.id} content result not written" in it.msg },
        )
    }

    @Test
    fun aCancelWritesTheResultsAlreadyReadWhenTheScanLockIsFree() = runBlocking {
        scanCartridges(3)
        val opened = CompletableDeferred<Unit>()
        val release = CompletableDeferred<Unit>()
        fx.tree.beforeQuery = { id ->
            if (id == "fs:gb/game001.gb") {
                opened.complete(Unit)
                runBlocking { release.await() }
            }
        }
        val run = async { readContent() }
        opened.await()
        // Cancel before releasing the hook (a cancelled reader must stop first, or the release hangs).
        run.cancel()
        release.complete(Unit)
        run.join()

        assertFalse("not read: the pass stopped before it", "fs:gb/game002.gb" in fx.tree.opened)
        assertTrue("read before the cancel and written on the way out", isDone("game000.gb"))
        assertFalse(isDone("game002.gb"))
        // Whatever was not written comes again on the next run; nothing is read twice.
        val doneBefore = listOf("game000.gb", "game001.gb", "game002.gb").filter { isDone(it) }
        readContent()
        assertTrue(fx.tree.opened.none { it.substringAfterLast('/') in doneBefore })
        assertEquals(ContentReadResult(), readContent())
    }

    @Test
    fun aDatabaseThatRefusesEveryWriteStopsThePassAndStampsNothing() = runTest {
        scanCartridges(3)
        fx.db.openHelper.writableDatabase.execSQL(
            "CREATE TRIGGER refuse_all BEFORE UPDATE OF fingerprint ON game BEGIN SELECT RAISE(ABORT, 'refused by the test'); END",
        )

        val error = try {
            readContent()
            null
        } catch (e: RuntimeException) {
            e
        }

        assertTrue("the pass stops with the database's error, got $error", error is android.database.sqlite.SQLiteConstraintException)
        for (i in 0 until 3) assertFalse(isDone("game%03d.gb".format(i)))
    }

    @Test
    fun aCancelWhileAScanHoldsTheLockDropsTheBatchAndTheNextRunReadsItAgain() = runBlocking {
        scanCartridges(3)
        // A pass of its own over the fixture's database, so the test can hold the scan lock.
        val scanLock = Mutex()
        val pass = { ContentPass(fx.db, fx.permissions, { fx.tree }, naming, scanLock, { fx.now }) }
        scanLock.lock()
        val opened = CompletableDeferred<Unit>()
        val release = CompletableDeferred<Unit>()
        fx.tree.beforeQuery = { id ->
            if (id == "fs:gb/game001.gb") {
                opened.complete(Unit)
                runBlocking { release.await() }
            }
        }
        fx.tree.opened.clear()
        val run = async { pass().run(ContentReadBudget()) }
        opened.await()
        // Cancel before releasing the hook (a cancelled reader must stop first, or the release hangs).
        run.cancel()
        release.complete(Unit)
        run.join()
        scanLock.unlock()
        fx.tree.beforeQuery = {}

        assertEquals(listOf("fs:gb/game000.gb", "fs:gb/game001.gb"), fx.tree.opened)
        for (i in 0 until 3) assertFalse(isDone("game%03d.gb".format(i)))
        assertTrue(
            "the dropped batch is logged",
            ShadowLog.getLogs().any { "2 results not written (the scan holds the lock)" in it.msg },
        )

        fx.tree.opened.clear()
        val next = pass().run(ContentReadBudget())
        assertEquals(3, next.written)
        assertEquals("the dropped files are read again", 3, fx.tree.opened.size)
        assertTrue(fx.tree.opened.containsAll(listOf("fs:gb/game000.gb", "fs:gb/game001.gb")))
    }

    private companion object {
        const val FILE_TIME = 1_600_000_000_000L
    }
}
