package com.plumemu.identify.fingerprint.cart

import com.plumemu.identify.fingerprint.CodeKind
import com.plumemu.identify.fingerprint.FingerprintReader
import com.plumemu.identify.fingerprint.Fingerprints
import com.plumemu.identify.fingerprint.TitleKind
import com.plumemu.identify.source.ByteArraySource
import com.plumemu.identify.source.CountingSource
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.nio.ByteBuffer
import java.nio.ByteOrder
import kotlin.random.Random

/** 3DS NCCH, NCSD and CIA headers from generated bytes; no real file, id or code. */
class N3dsReaderTest {
    private val reader = FingerprintReader()

    private fun read(bytes: ByteArray, name: String, system: String? = "n3ds"): Fingerprints =
        reader.read(ByteArraySource(bytes), name, system, FingerprintReader.Depth.QUICK)

    @Test fun cxiGivesItsGameCodeAndProgramId() {
        val read = read(ncch(GAME, "CTR-P-ZZZE"), "zork.cxi")
        assertEquals("ZZZE", read.productCode)
        assertEquals(CodeKind.N3DS, read.codeKind)
        assertEquals(GAME, read.titleId)
        assertEquals(TitleKind.BASE, read.titleKind)
        assertEquals(listOf("code:N3DS:ZZZE"), read.fixKeys())
    }

    @Test fun cardImageReadsPartitionZero() {
        val read = read(ncsd(ncch(GAME, "KTR-P-ZZZJ")), "zork.3ds")
        assertEquals("ZZZJ", read.productCode)
        assertEquals(GAME, read.titleId)
        val bigUnits = read(ncsd(ncch(GAME, "CTR-P-ZZZE"), unitShift = 1), "zork.cci", system = null)
        assertEquals("the media unit grows with the flag", "ZZZE", bigUnits.productCode)
    }

    @Test fun cardImageReadsOnlyItsHeaders() {
        val counting = CountingSource(ByteArraySource(ncsd(ncch(GAME, "CTR-P-ZZZE")) + ByteArray(1 shl 20)))
        reader.read(counting, "zork.3ds", "n3ds", FingerprintReader.Depth.QUICK)
        assertTrue("read ${counting.bytesRead} bytes", counting.bytesRead < 1024)
    }

    @Test fun updatesAndDlcHaveTheirKind() {
        assertEquals(TitleKind.UPDATE, read(ncch("0004000E00ABCD00", "CTR-P-ZZZE"), "u.cxi").titleKind)
        assertEquals(TitleKind.DLC, read(ncch("0004008C00ABCD00", "CTR-P-ZZZE"), "d.cxi").titleKind)
        assertEquals(TitleKind.BASE, read(ncch("0004000200ABCD00", "CTR-P-ZZZE"), "demo.cxi").titleKind)
    }

    @Test fun homebrewPlaceholderIsNoCode() {
        val read = read(ncch(GAME, "CTR-P-CTAP"), "homebrew.cxi")
        assertNull(read.productCode)
        assertEquals(GAME, read.titleId)
        assertTrue(read.notes.toString(), read.notes.any { "no game code" in it })
    }

    @Test fun decryptedCiaGivesCodeAndTitleId() {
        val read = read(cia(GAME, encrypted = false, content = ncch(GAME, "CTR-P-ZZZE")), "zork.cia")
        assertEquals(GAME, read.titleId)
        assertEquals("ZZZE", read.productCode)
    }

    @Test fun encryptedCiaGivesItsTitleIdOnly() {
        val read = read(cia(GAME, encrypted = true, content = ByteArray(0x200) { 0x5A }), "zork.cia")
        assertEquals("the TMD is never encrypted", GAME, read.titleId)
        assertNull(read.productCode)
        assertTrue(read.notes.toString(), read.notes.any { "encrypted with its title key" in it })
    }

    @Test fun garbageIsNoHeader() {
        val read = read(ByteArray(0x4000) { (it * 7).toByte() }, "zork.3ds")
        assertNull(read.titleId)
        assertTrue(read.notes.toString(), read.notes.any { "no valid n3ds header" in it })
    }

    @Test fun cutAndDamagedFilesGiveNotesNotExceptions() {
        val files = listOf(ncch(GAME, "CTR-P-ZZZE"), ncsd(ncch(GAME, "CTR-P-ZZZE")), cia(GAME, false, ncch(GAME, "CTR-P-ZZZE")))
        val random = Random(9)
        for (file in files) {
            for (length in listOf(0, 4, 0x100, 0x104, 0x150, 0x15F, 0x18F, 0x2040, 0x4000, file.size - 1)) {
                read(file.copyOf(minOf(length, file.size)), "cut.3ds") // must not throw
            }
            repeat(300) {
                val bytes = file.copyOf()
                repeat(3) { bytes[random.nextInt(bytes.size)] = random.nextInt(256).toByte() }
                read(bytes, "damaged.cia")
            }
        }
    }

    companion object {
        const val GAME = "0004000000ABCD00"

        /** An NCCH header: magic, program id (little-endian) and product code; rest zero. */
        fun ncch(programId: String, productCode: String): ByteArray {
            val b = ByteBuffer.allocate(0x200).order(ByteOrder.LITTLE_ENDIAN)
            b.position(0x100); b.put("NCCH".toByteArray())
            b.putLong(0x108, java.lang.Long.parseUnsignedLong(programId, 16))
            b.putLong(0x118, java.lang.Long.parseUnsignedLong(programId, 16))
            b.position(0x150); b.put(productCode.toByteArray())
            return b.array()
        }

        /** An NCSD card image with [partition] at 0x20 media units. */
        fun ncsd(partition: ByteArray, unitShift: Int = 0): ByteArray {
            val offset = 0x20 * (0x200 shl unitShift)
            val b = ByteBuffer.allocate(offset + partition.size).order(ByteOrder.LITTLE_ENDIAN)
            b.position(0x100); b.put("NCSD".toByteArray())
            b.putInt(0x120, 0x20)
            b.putInt(0x124, partition.size / 0x200)
            b.put(0x18E, unitShift.toByte())
            b.position(offset); b.put(partition)
            return b.array()
        }

        /** A CIA with a 0xA00-byte certificate chain, a 0x350-byte ticket, an RSA-2048 TMD and [content]. */
        fun cia(titleId: String, encrypted: Boolean, content: ByteArray): ByteArray {
            val certSize = 0xA00
            val ticketSize = 0x350
            val tmdSize = 0x140 + 0xC4 + 0x900 + 0x30
            fun align(v: Int) = (v + 63) / 64 * 64
            val tmdAt = align(0x2020) + align(certSize) + align(ticketSize)
            val contentAt = tmdAt + align(tmdSize)
            val b = ByteBuffer.allocate(contentAt + content.size).order(ByteOrder.LITTLE_ENDIAN)
            b.putInt(0, 0x2020).putShort(4, 0).putShort(6, 0)
            b.putInt(0x08, certSize).putInt(0x0C, ticketSize).putInt(0x10, tmdSize)
            b.putLong(0x18, content.size.toLong())
            b.order(ByteOrder.BIG_ENDIAN)
            b.putInt(tmdAt, 0x10004)
            val header = tmdAt + 0x140
            b.putLong(header + 0x4C, java.lang.Long.parseUnsignedLong(titleId, 16))
            b.putShort(header + 0x9E, 1)
            val chunk = header + 0xC4 + 0x900
            b.putShort(chunk + 6, if (encrypted) 1 else 0)
            b.putLong(chunk + 8, content.size.toLong())
            b.position(contentAt); b.put(content)
            return b.array()
        }
    }
}
